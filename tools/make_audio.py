# ───────────────────────────── mastering ─────────────────────────────

MUSIC_RMS_DBFS = -16.0


def _circular(fn, x: np.ndarray) -> np.ndarray:
    """Applies a filter to a loop as if it had always been looping, so the seam carries the
    filter's state across instead of clicking: run it over three copies, keep the middle."""
    n = len(x)
    return fn(np.tile(x, 3))[n: 2 * n]


def master(x: np.ndarray, loop: bool, lp: float | None = None, fade_out: float = 0.0005) -> np.ndarray:
    """Every music track ends here, so all three packs sit at the same loudness.

    Loudness is matched by RMS, not peak: the first build peak-normalised, which made the dense
    square-wave arcade tracks far louder than their meters said (the first device test put 50%
    phone volume at "sounds like 90%"). With RMS matched, switching packs never jumps the volume,
    and the in-app level decides how loud all of them are.
    """
    if lp:
        x = _circular(lambda y: lowpass(y, lp), x) if loop else lowpass(x, lp)
    x = x - np.mean(x)
    x = x * (10 ** (MUSIC_RMS_DBFS / 20) / (np.sqrt(np.mean(x ** 2)) + 1e-12))
    ceiling = 0.85
    x = ceiling * np.tanh(x / ceiling)  # a soft ceiling, never a hard clip
    if not loop:
        fo, fi = samples(fade_out), samples(0.002)
        x[-fo:] *= np.linspace(1, 0, fo)
        x[:fi] *= np.linspace(0, 1, fi)
    return x


def loop_room(x: np.ndarray, mix: float, tail: float = 0.8) -> np.ndarray:
    """[room] for a loop: the reverb tail of the last bar rings into the first."""
    return _circular(lambda y: room(y, mix, tail)[: len(y)], x)


def up(note: str, octaves: int = 1) -> str:
    return note[:-1] + str(int(note[-1]) + octaves)


# ───────────────────────────── softer instruments ─────────────────────────────

def saw(freq, n: int) -> np.ndarray:
    t, dt = phase(freq, n)
    return 2 * t - 1 - _polyblep(t, dt)


def epiano(note: str, seconds: float, vol=1.0, decay=1.4) -> np.ndarray:
    """A Rhodes-ish electric piano: two-operator FM whose brightness fades as the note does,
    with a slow tremolo. Nothing above a few kHz — the opposite of a square wave."""
    n = samples(seconds)
    t = np.arange(n) / SR
    f = hz(note)
    index = 1.4 * np.exp(-t / 0.35)
    tone = np.sin(2 * np.pi * f * t + index * np.sin(2 * np.pi * f * t))
    tone += 0.12 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t / 0.2)
    amp = np.exp(-t / decay) * (1 + 0.08 * np.sin(2 * np.pi * 4.2 * t))
    return tone * amp * env(n, 0.004, 0, 1, 0.08) * vol


def epiano_chord(notes, seconds: float, vol=0.2, strum=0.012, decay=1.4) -> np.ndarray:
    out = np.zeros(samples(seconds + strum * len(notes)))
    for i, nm in enumerate(notes):
        place(out, epiano(nm, seconds, vol, decay), i * strum)
    return out


def bell(note: str, seconds: float, vol=1.0) -> np.ndarray:
    """A soft glockenspiel: a sine with two inharmonic partials that die first."""
    n = samples(seconds)
    t = np.arange(n) / SR
    f = hz(note)
    x = np.sin(2 * np.pi * f * t) * np.exp(-t / 0.9)
    x += 0.25 * np.sin(2 * np.pi * 2.76 * f * t) * np.exp(-t / 0.25)
    x += 0.08 * np.sin(2 * np.pi * 5.4 * f * t) * np.exp(-t / 0.08)
    return x * env(n, 0.002, 0, 1, 0.05) * vol


def pad(notes, seconds: float, vol=0.1, attack=0.6, release=0.8, bright=1400, kind="soft") -> np.ndarray:
    """A sustained chord. "soft" is detuned sine+triangle (warm, no edge); "saw" is a supersaw
    for the synthwave pack, filtered so it glows rather than buzzes."""
    n = samples(seconds)
    out = np.zeros(n)
    for nm in notes:
        f = hz(nm)
        for detune in (0.997, 1.0, 1.003):
            if kind == "saw":
                out += saw(f * detune, n)
            else:
                out += sine(f * detune, n) * 0.7 + triangle(f * detune, n) * 0.3
    out = lowpass(out / (3 * len(notes)), bright)
    return out * env(n, attack, 0, 1, release) * vol


def sub(note: str, seconds: float, vol=0.5) -> np.ndarray:
    n = samples(seconds)
    f = hz(note)
    return (sine(f, n) + 0.15 * sine(2 * f, n)) * env(n, 0.01, 0, 1, 0.06) * vol


def soft_kick(vol=1.0) -> np.ndarray:
    n = samples(0.25)
    f = 42 + 60 * np.exp(-np.arange(n) / (0.04 * SR))
    return sine(f, n) * exp_decay(n, 0.09) * vol


def brush(vol=1.0) -> np.ndarray:
    """A brushed snare: band-limited noise, no crack, nothing above 5 kHz."""
    n = samples(0.22)
    return bandpass(noise(n), 500, 4500) * env(n, 0.012, 0.05, 0.35, 0.12) * vol


def gated_snare(vol=1.0) -> np.ndarray:
    """The 80s snare: a fat hit with a big room, cut off short."""
    n = samples(0.35)
    body = triangle(180, n) * exp_decay(n, 0.04) * 0.6
    rattle = bandpass(noise(n), 900, 6000) * exp_decay(n, 0.12)
    x = room(body + rattle, 0.45, 0.0)[:n]
    return x * env(n, 0.001, 0, 1, 0.1) * vol


def synth_lead(note: str, seconds: float, vol=0.3, cutoff=3200) -> np.ndarray:
    n = samples(seconds)
    t = np.arange(n) / SR
    f = hz(note) * (1 + 0.006 * np.clip(t / 0.3, 0, 1) * np.sin(2 * np.pi * 5.2 * t))
    x = saw(f, n) * 0.6 + square(f * 1.004, n, 0.5) * 0.4
    return lowpass(x, cutoff) * env(n, 0.01, 0.12, 0.7, 0.08) * vol


def synth_bass(note: str, seconds: float, vol=0.5) -> np.ndarray:
    n = samples(seconds)
    x = saw(hz(note), n) * 0.7 + sine(hz(note), n) * 0.5
    return lowpass(x, 650) * env(n, 0.004, 0.08, 0.6, 0.03) * vol


def pluck(note: str, seconds: float, vol=0.12, cutoff=2600) -> np.ndarray:
    n = samples(seconds)
    x = saw(hz(note), n) * exp_decay(n, 0.12)
    return lowpass(x, cutoff) * env(n, 0.002, 0, 1, 0.02) * vol


