def nd_victory() -> np.ndarray:
    tr = Track(110, 20, loop=False)
    for i in range(8):  # the build
        tr.add(i * 0.25, gated_snare(0.12 + i * 0.04))
    tr.add(0, pad(["A3", "C4", "E4"], tr.seconds(2), vol=0.08, attack=1.2, release=0.1, bright=1500, kind="saw"))
    lead = [(None, 2), ("C5", .5), ("E5", .5), ("G5", .5), ("C6", .5),
            ("E6", 2), ("D6", 1), ("C6", 1), ("D6", 1.5), ("B5", .5), ("G5", 2), ("C6", 6)]
    tr.melody(0, lead, lambda nm, secs: synth_lead(nm, secs * 0.95, 0.26, cutoff=3800))
    for b, ch, root, ln in ((2, ["C4", "E4", "G4"], "C2", 4), (6, ["G3", "B3", "D4"], "G1", 4),
                            (10, ["C4", "E4", "G4", "C5"], "C2", 6)):
        tr.add(b, pad(ch, tr.seconds(ln), vol=0.12, attack=0.05, release=1.2, bright=2600, kind="saw"))
        for i in range(int(ln * 2)):
            tr.add(b + i * 0.5, synth_bass(root, tr.seconds(0.45), 0.36 if i < ln * 2 - 2 else 0.2))
        tr.add(b, kick(0.9))
        tr.add(b, crash(0.2))
        tr.add(b + 1, gated_snare(0.35))
        tr.add(b + 3, gated_snare(0.35))
    out = room(tr.buf, 0.25, 1.5)
    return master(out[: samples(tr.seconds(16) + 1.5)], loop=False, lp=7000, fade_out=2.0)


