"""
Generates every sound effect and music track CONTINUE? ships, from nothing but maths.

Why synthesise instead of downloading a pack: docs/03-DESIGN-SYSTEM.md §6 requires audio that is
"original or CC0 with a documented licence", and the demo-video rules ban unlicensed audio. A
file this script writes has no upstream licence to track, no attribution to keep in sync, and
can be regenerated byte-for-byte by anyone reading the public repo. The output is dedicated to
the public domain under CC0 1.0 (see docs/AUDIO-LICENSE.md).

    pip install numpy scipy soundfile
    python tools/make_audio.py            # writes app/src/main/res/raw/{sfx,music}_*.ogg

Three music packs (ARCADE, AFTER HOURS, NEON DRIVE) of four tracks each, plus 14 effects.

Everything is deterministic (fixed noise seed), mono, 44.1 kHz, Ogg Vorbis — the one compressed
format both SoundPool and MediaPlayer decode on every API level the app supports (minSdk 26).
"""

from __future__ import annotations

import pathlib

import numpy as np
import soundfile as sf
from scipy.signal import butter, lfilter

SR = 44_100
OUT = pathlib.Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res" / "raw"
RNG = np.random.default_rng(0xC0FFEE)

# ───────────────────────────── primitives ─────────────────────────────

NOTE_INDEX = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8,
              "A": 9, "A#": 10, "B": 11, "Db": 1, "Eb": 3, "Gb": 6, "Ab": 8, "Bb": 10}


def hz(note: str) -> float:
    """'A4' -> 440.0, 'C#5' -> 554.37."""
    name, octave = note[:-1], int(note[-1])
    midi = 12 * (octave + 1) + NOTE_INDEX[name]
    return 440.0 * 2 ** ((midi - 69) / 12)


def samples(seconds: float) -> int:
    return max(1, int(round(seconds * SR)))


def _polyblep(t: np.ndarray, dt: np.ndarray) -> np.ndarray:
    """Band-limits a hard edge so high notes don't alias into a harsh fizz."""
    out = np.zeros_like(t)
    lo = t < dt
    x = t[lo] / dt[lo]
    out[lo] = 2 * x - x * x - 1
    hi = t > 1 - dt
    x = (t[hi] - 1) / dt[hi]
    out[hi] = x * x + 2 * x + 1
    return out


def phase(freq, n: int) -> tuple[np.ndarray, np.ndarray]:
    f = np.broadcast_to(np.asarray(freq, dtype=float), (n,))
    dt = f / SR
    return np.cumsum(dt) % 1.0, dt


def square(freq, n: int, duty: float = 0.5) -> np.ndarray:
    t, dt = phase(freq, n)
    out = np.where(t < duty, 1.0, -1.0)
    out += _polyblep(t, dt)
    out -= _polyblep((t - duty) % 1.0, dt)
    return out


def triangle(freq, n: int) -> np.ndarray:
    t, _ = phase(freq, n)
    return 4 * np.abs(t - 0.5) - 1


def sine(freq, n: int) -> np.ndarray:
    t, _ = phase(freq, n)
    return np.sin(2 * np.pi * t)


def noise(n: int) -> np.ndarray:
    return RNG.uniform(-1, 1, n)


def env(n: int, attack=0.005, decay=0.0, sustain=1.0, release=0.02) -> np.ndarray:
    """ADSR where the note's length *includes* the release, so notes never overhang their slot."""
    a, d, r = samples(attack), samples(decay), samples(release)
    s = max(0, n - a - d - r)
    e = np.concatenate([
        np.linspace(0, 1, a, endpoint=False),
        np.linspace(1, sustain, d, endpoint=False),
        np.full(s, sustain),
        np.linspace(sustain, 0, r),
    ])
    return np.pad(e, (0, max(0, n - len(e))))[:n]


def exp_decay(n: int, seconds: float) -> np.ndarray:
    return np.exp(-np.arange(n) / (seconds * SR))


def lowpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = butter(order, cutoff / (SR / 2), btype="low")
    return lfilter(b, a, x)


def highpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = butter(order, cutoff / (SR / 2), btype="high")
    return lfilter(b, a, x)


def bandpass(x: np.ndarray, lo: float, hi: float, order: int = 2) -> np.ndarray:
    b, a = butter(order, [lo / (SR / 2), hi / (SR / 2)], btype="band")
    return lfilter(b, a, x)


def echo(x: np.ndarray, delay: float, feedback: float, tail: float = 0.0) -> np.ndarray:
    d = samples(delay)
    y = np.pad(x, (0, samples(tail)))
    den = np.zeros(d + 1)
    den[0], den[d] = 1.0, -feedback
    return lfilter([1.0], den, y)


def room(x: np.ndarray, mix: float = 0.18, tail: float = 0.6) -> np.ndarray:
    """A small Schroeder-style room: four parallel combs, softened. Just enough air."""
    y = np.pad(x, (0, samples(tail)))
    wet = np.zeros_like(y)
    for delay_ms, fb in ((29.7, 0.72), (37.1, 0.70), (41.1, 0.68), (43.7, 0.66)):
        d = samples(delay_ms / 1000)
        den = np.zeros(d + 1)
        den[0], den[d] = 1.0, -fb
        wet += lfilter([1.0], den, y)
    wet = lowpass(wet / 4, 4500)
    return y * (1 - mix) + wet * mix


def place(buf: np.ndarray, sound: np.ndarray, at: float, wrap: bool = False) -> None:
    """Mixes [sound] into [buf] at [at] seconds. With [wrap], a tail past the end loops round."""
    start = samples(at) if at > 0 else 0
    end = start + len(sound)
    if end <= len(buf):
        buf[start:end] += sound
    elif wrap:
        head = len(buf) - start
        buf[start:] += sound[:head]
        rest = sound[head:]
        while len(rest):
            chunk = rest[: len(buf)]
            buf[: len(chunk)] += chunk
            rest = rest[len(chunk):]
    else:
        buf[start:] += sound[: len(buf) - start]


def finish(x: np.ndarray, peak: float = 0.8, fade_in: float = 0.002, fade_out: float = 0.01) -> np.ndarray:
    x = np.tanh(x * 1.1) / np.tanh(1.1)  # gentle glue, never a hard clip
    x = x - np.mean(x)
    fi, fo = samples(fade_in), samples(fade_out)
    x[:fi] *= np.linspace(0, 1, fi)
    x[-fo:] *= np.linspace(1, 0, fo)
    m = np.max(np.abs(x))
    return x * (peak / m) if m > 0 else x


def write(name: str, x: np.ndarray) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.ogg"
    # Written in blocks: libsndfile's Vorbis encoder hangs when handed a long file in one call.
    data = x.astype(np.float32)
    with sf.SoundFile(path, "w", SR, 1, format="OGG", subtype="VORBIS") as f:
        for i in range(0, len(data), 4096):
            f.write(data[i:i + 4096])
    print(f"{path.name:28s} {len(x) / SR:6.2f}s {path.stat().st_size / 1024:7.1f} KB")


# ───────────────────────────── instruments ─────────────────────────────

def pulse_note(note: str, seconds: float, duty=0.5, vol=1.0, vibrato=0.0, attack=0.004,
               release=0.03, decay=0.08, sustain=0.7) -> np.ndarray:
    n = samples(seconds)
    f = hz(note)
    if vibrato:
        t = np.arange(n) / SR
        # Vibrato fades in, the way a player leans into a held note.
        depth = vibrato * np.clip(t / 0.25, 0, 1)
        f = f * (1 + depth * np.sin(2 * np.pi * 5.5 * t))
    return square(f, n, duty) * env(n, attack, decay, sustain, release) * vol


def tri_note(note: str, seconds: float, vol=1.0, release=0.02) -> np.ndarray:
    n = samples(seconds)
    return triangle(hz(note), n) * env(n, 0.003, 0.0, 1.0, release) * vol


def kick(vol=1.0) -> np.ndarray:
    n = samples(0.18)
    f = 45 + 110 * np.exp(-np.arange(n) / (0.03 * SR))
    click = highpass(noise(n), 2000) * exp_decay(n, 0.004) * 0.3
    return (sine(f, n) * exp_decay(n, 0.07) + click) * vol


def snare(vol=1.0) -> np.ndarray:
    n = samples(0.16)
    body = triangle(190, n) * exp_decay(n, 0.03) * 0.5
    rattle = bandpass(noise(n), 1500, 9000) * exp_decay(n, 0.05)
    return (body + rattle) * vol


def hat(vol=1.0, open_=False) -> np.ndarray:
    """Half the level of the first build: the first listen called the arcade pack "lots of
    high-pitch noise", and most of that was hats."""
    n = samples(0.18 if open_ else 0.04)
    return highpass(noise(n), 7000) * exp_decay(n, 0.06 if open_ else 0.012) * vol * 0.5


def crash(vol=1.0) -> np.ndarray:
    n = samples(1.6)
    return highpass(noise(n), 4000) * exp_decay(n, 0.45) * vol


# ───────────────────────────── sequencer ─────────────────────────────

class Track:
    """A beat-addressed mix bus. Loops wrap their tails so the seam is inaudible."""

    def __init__(self, bpm: float, beats: float, loop: bool):
        self.spb = 60.0 / bpm
        self.loop = loop
        self.buf = np.zeros(samples(beats * self.spb) + (0 if loop else samples(3.0)))

    def add(self, beat: float, sound: np.ndarray) -> None:
        place(self.buf, sound, beat * self.spb, wrap=self.loop)

    def seconds(self, beats: float) -> float:
        return beats * self.spb

    def melody(self, start: float, notes, voice) -> float:
        """notes: [(note|None, beats)]. Returns the beat after the phrase."""
        b = start
        for note, length in notes:
            if note is not None:
                self.add(b, voice(note, self.seconds(length)))
            b += length
        return b


CHORDS = {
    "C": ["C", "E", "G"], "Am": ["A", "C", "E"], "F": ["F", "A", "C"], "G": ["G", "B", "D"],
    "Em": ["E", "G", "B"], "Dm": ["D", "F", "A"], "E": ["E", "G#", "B"], "G7": ["G", "B", "F"],
    "Fmaj7": ["F", "A", "E"], "Dm7": ["D", "F", "C"], "Gm7": ["G", "Bb", "F"], "C7": ["C", "E", "Bb"],
    "Bbmaj7": ["Bb", "D", "A"],
}


def arp(track: Track, bar_beat: float, chord: str, octave: int, beats=4, step=0.25, vol=0.16,
        duty=0.125, pattern=(0, 1, 2, 1)) -> None:
    tones = CHORDS[chord]
    i = 0
    b = bar_beat
    while b < bar_beat + beats - 1e-6:
        idx = pattern[i % len(pattern)]
        note = f"{tones[idx % 3]}{octave + idx // 3}"
        track.add(b, pulse_note(note, track.seconds(step) * 0.9, duty=duty, vol=vol,
                                decay=0.05, sustain=0.4, release=0.01))
        b += step
        i += 1


def bass(track: Track, bar_beat: float, root: str, octave=2, beats=4, vol=0.55, style="octave") -> None:
    b = bar_beat
    i = 0
    while b < bar_beat + beats - 1e-6:
        if style == "octave":
            note = f"{root}{octave + (i % 2)}"
            length = 0.5
        else:  # "pulse": driving repeated eighths
            note = f"{root}{octave}"
            length = 0.5
        track.add(b, tri_note(note, track.seconds(length) * 0.92, vol=vol))
        b += length
        i += 1


def drums(track: Track, bar_beat: float, beats=4, kick_on=(0, 2), snare_on=(1, 3), hats=0.5,
          vol=1.0) -> None:
    for k in kick_on:
        track.add(bar_beat + k, kick(0.9 * vol))
    for s in snare_on:
        track.add(bar_beat + s, snare(0.45 * vol))
    if hats:
        b = 0.0
        while b < beats - 1e-6:
            track.add(bar_beat + b, hat(0.22 * vol if b % 1 == 0 else 0.14 * vol))
            b += hats


# ───────────────────────────── sound effects ─────────────────────────────

def sfx_coin() -> np.ndarray:
    """The coin. Two pulse notes a fourth apart — the most recognisable sound in arcades."""
    a = square(hz("B5"), samples(0.075), 0.5) * 0.8
    n = samples(0.42)
    b = square(hz("E6"), n, 0.5) * exp_decay(n, 0.13)
    return finish(room(np.concatenate([a, b]), 0.12, 0.25))


def sfx_coin_drop() -> np.ndarray:
    """A payout: a cascade of coins landing, for a RevenueCat grant arriving."""
    buf = np.zeros(samples(1.4))
    coin = sfx_coin()
    for i, at in enumerate((0.0, 0.09, 0.17, 0.24, 0.30, 0.36, 0.42)):
        pitch = 1 + 0.03 * (i % 3)
        idx = np.clip((np.arange(int(len(coin) / pitch)) * pitch).astype(int), 0, len(coin) - 1)
        place(buf, coin[idx] * (0.9 - i * 0.07), at)
    return finish(buf)


def sfx_lever() -> np.ndarray:
    """A slot-machine lever: ratchet teeth on the way down, then the mechanism bottoming out."""
    buf = np.zeros(samples(0.55))
    for i in range(5):
        n = samples(0.018)
        tick = bandpass(noise(n), 2500, 7000) * exp_decay(n, 0.004) * (0.35 + 0.05 * i)
        place(buf, tick, i * 0.032)
    n = samples(0.35)
    f = 70 * np.exp(-np.arange(n) / (0.12 * SR)) + 42
    thud = sine(f, n) * exp_decay(n, 0.09) * 1.2
    clank = bandpass(noise(n), 400, 2400) * exp_decay(n, 0.025) * 0.6
    metal = (square(hz("D4"), n, 0.3) + square(hz("A4") * 1.01, n, 0.3)) * exp_decay(n, 0.05) * 0.12
    place(buf, thud + clank + metal, 0.17)
    return finish(room(buf, 0.15, 0.3))


def sfx_deal() -> np.ndarray:
    """A card leaving the shoe: a short paper swish whose band sweeps down."""
    n = samples(0.16)
    x = noise(n)
    t = np.arange(n) / n
    lo_band = bandpass(x, 900, 3000) * t
    hi_band = bandpass(x, 3000, 9000) * (1 - t)
    e = env(n, 0.012, 0.03, 0.5, 0.08)
    return finish((lo_band + hi_band) * e)


def sfx_flip() -> np.ndarray:
    """A card turning face up: two tight snaps."""
    buf = np.zeros(samples(0.12))
    for at, v in ((0.0, 0.7), (0.045, 1.0)):
        n = samples(0.03)
        place(buf, bandpass(noise(n), 1800, 8000) * exp_decay(n, 0.006) * v, at)
    return finish(buf)


def sfx_whoosh() -> np.ndarray:
    """A card flung away (SKIP / NOT TONIGHT)."""
    n = samples(0.28)
    x = noise(n)
    t = np.linspace(0, 1, n)
    y = np.zeros(n)
    # A bank of bands swept downward, crossfaded — cheap and convincing.
    for lo, hi, w in ((4000, 9000, 1 - t), (1800, 4000, np.sin(np.pi * t)), (600, 1800, t)):
        y += bandpass(x, lo, hi) * w
    return finish(y * env(n, 0.04, 0.0, 1.0, 0.16))


def sfx_select() -> np.ndarray:
    """A confident pick (PLAYING IT, a RANK choice): a quick rising major arpeggio."""
    notes = ["C5", "E5", "G5", "C6"]
    parts = [pulse_note(nm, 0.045, duty=0.25, decay=0.02, sustain=0.8, release=0.008) for nm in notes[:-1]]
    parts.append(pulse_note(notes[-1], 0.22, duty=0.25, decay=0.1, sustain=0.3, release=0.1))
    return finish(room(np.concatenate(parts), 0.15, 0.3))


def sfx_blip() -> np.ndarray:
    """The button press. Deliberately tiny — it plays more than anything else."""
    n = samples(0.045)
    f = np.linspace(1500, 1100, n)
    return finish(triangle(f, n) * exp_decay(n, 0.012), peak=0.6)


def sfx_tick() -> np.ndarray:
    """A detent — one card passing in STACK, one letter of GAME CLEARED typing."""
    n = samples(0.02)
    return finish(bandpass(noise(n), 2500, 6500) * exp_decay(n, 0.003) + square(2200, n, 0.5) * exp_decay(n, 0.002) * 0.3, peak=0.55)


def sfx_error() -> np.ndarray:
    """Can't afford it / declined. Two low buzzes, falling — informative, not scolding."""
    a = pulse_note("E3", 0.09, duty=0.25, decay=0.02, sustain=0.8, release=0.02)
    gap = np.zeros(samples(0.03))
    b = pulse_note("C3", 0.16, duty=0.25, decay=0.05, sustain=0.6, release=0.06)
    return finish(lowpass(np.concatenate([a, gap, b]), 2500), peak=0.7)


def sfx_add() -> np.ndarray:
    """A game saved into the pile — an "item get" chime with a little echo."""
    notes = ["G5", "B5", "D6", "G6"]
    parts = [pulse_note(nm, 0.06, duty=0.5, decay=0.02, sustain=0.7, release=0.01) for nm in notes[:-1]]
    parts.append(pulse_note(notes[-1], 0.3, duty=0.5, decay=0.15, sustain=0.25, release=0.12))
    x = np.concatenate(parts) * 0.8
    return finish(room(echo(x, 0.11, 0.3, 0.4), 0.12, 0.2))


def sfx_friend() -> np.ndarray:
    """"A NEW CHALLENGER HAS ENTERED" — a friend's pile arriving."""
    buf = np.zeros(samples(1.1))
    for at, nm, ln in ((0.0, "A4", 0.1), (0.1, "A4", 0.1), (0.2, "E5", 0.1), (0.3, "A5", 0.45)):
        place(buf, pulse_note(nm, ln, duty=0.25, vibrato=0.01, decay=0.05, sustain=0.6, release=0.06), at)
        place(buf, pulse_note(nm, ln, duty=0.125, vibrato=0.0, decay=0.05, sustain=0.6, release=0.06) * 0.35, at + 0.012)
    place(buf, crash(0.25)[: samples(0.8)], 0.3)
    return finish(room(buf, 0.18, 0.4))


def sfx_powerup() -> np.ndarray:
    """PRO unlocked. The biggest effect in the app: a sweep up into a held major chord."""
    n = samples(0.5)
    t = np.arange(n) / n
    f = hz("C4") * 2 ** (t * 2)  # two octaves up
    stepped = np.round(np.log2(f / hz("C4")) * 12) / 12  # quantised like an old sound chip
    sweep = square(hz("C4") * 2 ** stepped, n, 0.25) * 0.6
    m = samples(0.9)
    chord = sum(square(hz(nm), m, 0.5) * 0.3 for nm in ("C6", "E6", "G6")) * exp_decay(m, 0.35)
    chord += triangle(hz("C4"), m) * exp_decay(m, 0.4) * 0.5
    x = np.concatenate([sweep, chord])
    place(x, crash(0.35)[: len(x) - n], 0.5)
    return finish(room(x, 0.2, 0.6))


def sfx_crt_on() -> np.ndarray:
    """A CRT powering on: the degauss thunk, a rising hum, static that settles."""
    total = samples(1.3)
    buf = np.zeros(total)
    n = samples(0.4)
    thunk = sine(55 + 40 * np.exp(-np.arange(n) / (0.05 * SR)), n) * exp_decay(n, 0.12)
    place(buf, thunk * 1.0, 0.0)
    place(buf, bandpass(noise(n), 200, 1200) * exp_decay(n, 0.04) * 0.5, 0.0)
    m = samples(1.1)
    t = np.arange(m) / m
    hum_f = 60 + 60 * t
    hum = (sine(hum_f, m) * 0.5 + sine(hum_f * 2, m) * 0.25) * np.sin(np.pi * np.clip(t * 1.2, 0, 1)) * 0.35
    place(buf, hum, 0.1)
    static = highpass(noise(m), 3000) * (np.exp(-t * 4)) * 0.35
    place(buf, static, 0.12)
    return finish(buf, fade_out=0.15)


# ───────────────────────────── music ─────────────────────────────

def lead(duty=0.5, vol=0.34, vibrato=0.006):
    return lambda note, secs: pulse_note(note, secs * 0.92, duty=duty, vol=vol, vibrato=vibrato,
                                         decay=0.08, sustain=0.65, release=0.04)


def music_title() -> np.ndarray:
    """Attract mode, for the cold open. Bright, 132 bpm, C major, a 16-bar loop."""
    tr = Track(132, 64, loop=True)
    progression = ["C", "Am", "F", "G", "C", "Am", ("F", "G"), "C",
                   "F", "G", "Em", "Am", "F", "G", "C", "G"]
    for bar, chord in enumerate(progression):
        b = bar * 4
        halves = chord if isinstance(chord, tuple) else (chord, chord)
        for h, ch in enumerate(halves):
            arp(tr, b + h * 2, ch, 4, beats=2, vol=0.12)
            bass(tr, b + h * 2, CHORDS[ch][0], octave=2, beats=2, vol=0.5)
        drums(tr, b, vol=0.9)
    phrase_a = [
        ("E5", .5), ("G5", .5), ("C6", 1), ("B5", .5), ("G5", .5), ("E5", 1),
        ("A5", 1.5), ("G5", .5), ("E5", 1), ("C5", 1),
        ("F5", .5), ("A5", .5), ("C6", 1), ("A5", .5), ("F5", .5), ("A5", 1),
        ("G5", 1.5), ("F5", .5), ("E5", 1), ("D5", 1),
        ("E5", .5), ("G5", .5), ("C6", 1), ("D6", .5), ("C6", .5), ("G5", 1),
        ("A5", 1), ("C6", 1), ("E6", 1.5), ("D6", .5),
        ("C6", 1), ("A5", 1), ("B5", 1), ("D6", 1),
        ("C6", 3), (None, 1),
    ]
    phrase_b = [
        ("A5", .5), ("C6", .5), ("F6", 1), ("E6", .5), ("D6", .5), ("C6", 1),
        ("B5", .5), ("D6", .5), ("G6", 1), ("F6", .5), ("E6", .5), ("D6", 1),
        ("E6", 1), ("B5", 1), ("G5", 1), ("B5", 1),
        ("C6", 1.5), ("B5", .5), ("A5", 2),
        ("F5", .5), ("A5", .5), ("C6", .5), ("F6", .5), ("E6", 1), ("C6", 1),
        ("D6", .5), ("B5", .5), ("G5", .5), ("B5", .5), ("D6", 1), ("G6", 1),
        ("E6", 1), ("D6", .5), ("C6", .5), ("D6", 1), ("E6", 1),
        ("D6", 2), ("B5", 1), ("G5", 1),
    ]
    b = tr.melody(0, phrase_a, lead())
    tr.melody(b, phrase_b, lead())
    # A quiet echo voice an octave down gives the lead body without a second melody to learn.
    b = tr.melody(0.01, [(n and n[:-1] + str(int(n[-1]) - 1), l) for n, l in phrase_a], lead(0.25, 0.1, 0))
    tr.melody(b, [(n and n[:-1] + str(int(n[-1]) - 1), l) for n, l in phrase_b], lead(0.25, 0.1, 0))
    return master(tr.buf, loop=True, lp=6000)


def music_continue() -> np.ndarray:
    """The CONTINUE? screen: minor, ticking, patient. An 8-bar loop at 112 bpm."""
    tr = Track(112, 32, loop=True)
